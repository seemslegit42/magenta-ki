export type AvfDomain = 'logistics' | 'customer_support' | 'marketing' | 'compliance' | 'healthcare' | 'supply_chain' | 'custom';

export type AgentAutonomy = 'supervised' | 'semi_autonomous' | 'fully_autonomous';
export type AgentStatus = 'active' | 'learning' | 'paused' | 'locked';

export interface UAVDefinition {
  id: string;
  name: string;
  domain: AvfDomain;
  description: string;
  baseValue: number; // V_base (USD)
  measurementUnit: string;
  verificationProof: string;
  completedCount: number;
  compoundingRate: number; // annual value appreciation %
  humanAlternativeCost: number;
}

export interface AgentDescriptor {
  id: string;
  name: string;
  role: string;
  domain: AvfDomain;
  autonomy: AgentAutonomy;
  status: AgentStatus;
  uavType: string;
  cyclesCompleted: number;
  learningVelocity: number; // experiments/hr
  alignmentScorePct: number;
  biasRiskPct: number;
  killSwitchEngaged: boolean;
  registeredDate: string;
}

export interface RevenueProjectionParams {
  baseValueUav: number; // V_base
  initialAgents: number; // N_agents
  annualAgentGrowthPct: number;
  compoundingMultiplier: number; // M_c (> 1)
  initialAdoptionFactor: number; // F_adopt (0 to 1)
  yearsToFullAdoption: number;
}

export interface YearlyProjectionRow {
  year: number;
  scenario: 'low' | 'medium' | 'high' | 'baseline' | 'custom';
  baseValue: number;
  agentCount: number;
  compoundingMultiplier: number;
  adoptionFactor: number;
  projectedRevenue: number;
  linearRevenue: number; // Without compounding
  intelligencePremium: number; // Extra revenue generated by compounding
  commentary: string;
}

export interface LegacyComparisonItem {
  id: string;
  model: string;
  coreConcept: string;
  keyMetrics: string[];
  primaryValueDriver: string;
  scalabilityModel: string;
  fitnessForAgentic: 'Low' | 'High' | 'Incompatible';
  criticalFlaw: string;
}

export interface RoicMetrics {
  infrastructureInvestment: number; // USD invested in feedback loops & data pipelines
  accumulatedUavGain: number; // USD value growth from compounded intelligence
  currentRoic: number; // Gain / Investment
  flywheelRpm: number;
  experimentVelocityPerHour: number;
}
